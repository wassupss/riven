// The app's own commands are refused to remote pages (ours is served from
// http://127.0.0.1) unless a capability allows them. Rather than keep a second
// list by hand, every #[tauri::command] under src/commands goes into the
// permission set `rust-main`, which capabilities/app.json grants to the app's
// webviews only.
use std::fmt::Write;

fn commands() -> Vec<String> {
  let mut out = Vec::new();
  let mut files: Vec<_> = std::fs::read_dir("src/commands").unwrap().flatten().map(|e| e.path()).collect();
  files.sort();
  for f in files {
    println!("cargo:rerun-if-changed={}", f.display());
    let src = std::fs::read_to_string(&f).unwrap();
    let mut armed = false;
    for line in src.lines() {
      let t = line.trim();
      if t.starts_with("#[tauri::command") {
        armed = true;
      } else if armed && t.contains("fn ") {
        let name = t.split("fn ").nth(1).unwrap().split(|c: char| c == '(' || c == '<').next().unwrap().trim();
        out.push(name.to_string());
        armed = false;
      }
    }
  }
  out
}

fn main() {
  println!("cargo:rerun-if-changed=src/commands");
  let cmds = commands();
  let mut toml = String::from(
    "# Generated by build.rs from the #[tauri::command]s in src/commands. Do not edit.\n\n[[set]]\nidentifier = \"rust-main\"\ndescription = \"Every command of riven's Rust main.\"\npermissions = [\n",
  );
  for c in &cmds {
    let _ = writeln!(toml, "  \"allow-{}\",", c.replace('_', "-"));
  }
  toml.push_str("]\n");
  for c in &cmds {
    let _ = write!(
      toml,
      "\n[[permission]]\nidentifier = \"allow-{}\"\ndescription = \"Allows {c}.\"\ncommands.allow = [\"{c}\"]\n",
      c.replace('_', "-")
    );
  }
  std::fs::create_dir_all("permissions").unwrap();
  let path = "permissions/rust-main.toml";
  if std::fs::read_to_string(path).ok().as_deref() != Some(toml.as_str()) {
    std::fs::write(path, toml).unwrap();
  }
  tauri_build::build()
}
